<?php

namespace App\Controllers\colors;

use App\Controllers\scheme\ControllerScheme;
use App\Models\ColorModel\ColorModel;


class colors extends ControllerScheme
{
    const string singleName = 'رنگ';
    const string pluralName = 'رنگ ها';
    protected string $defaultModel = ColorModel::class;

    public function main()
    {
        view->setPageTitle(self::pluralName);
        view->setSingleName(self::singleName);
        view->setPluralName(self::pluralName);
        view->ui([
            'vendors/js/tables/datatable/datatables.min',
            'vendors/js/tables/datatable/dataTables.bootstrap4.min',
            'vendors/js/tables/datatable/dataTables.buttons.min',
            'vendors/js/tables/datatable/buttons.html5.min',
            'vendors/js/tables/datatable/buttons.print.min',
            'vendors/js/tables/datatable/buttons.bootstrap.min',
            'vendors/js/tables/datatable/jszip.min',
            'vendors/js/tables/datatable/pdfmake.min',
            'vendors/js/tables/datatable/vfs_fonts',
            'vendors/js/tables/datatable/buttons.colVis.min',
            'js/colors/colors',
        ],
            ['vendors/css/tables/datatable/datatables.min'], [
                'colors' => ColorModel::all()
            ])->display('colors/colors.tpl');
    }

    public function addIndex()
    {
        view->setPageTitle(self::pluralName);
        view->setSingleName(self::singleName);
        view->setPluralName(self::pluralName);
        view->ui([
            'js/colors/add-colors',
        ])->display('colors/add-colors.tpl');
    }

    public function editIndex($id)
    {
        view->setPageTitle(self::pluralName);
        view->setSingleName(self::singleName);
        view->setPluralName(self::pluralName);
        view->setModel(ColorModel::query()->find($id));
        view->ui([
            'js/colors/edit-colors',
        ])->display('colors/edit-colors.tpl');
    }

    public function edit($id)
    {
        if (!isset($this->requestArray()['color_status'])) {
            $this->changeRequestValues('color_status', 0);
        }
        parent::edit($id); // TODO: Change the autogenerated stub
    }

    public function getColors()
    {
        $idInput = $this->requestArray()['idSelect'];
        $idValeInput = $this->requestArray()['idValeInput'];
        $get = ColorModel::query()->where(['color_status' => 1])->get();
        $output = [];
        $output[] = '<style>
        .swal2-html-container{
            overflow: hidden;
        }
        </style>';
        $output[] = '<div class="row mt-3" style="height: 600px;overflow-x: auto">
      
        ';
        foreach ($get as $item) {
            $output[] = '<div class="col-md-2">
                           <button class="btn btn-sm mb-1 w-100 colorButton" style="background-color: ' . $item->hex . ';color:#ffff" data-select="' . $idInput . '" data-ral="' . $item->ral_code . '" data-value="' . $idValeInput . '" data-color="' . $item->id . '" data-hex="' . $item->hex . '"><kbd>' . $item->ral_code . '</kbd><br><kbd>' . $item->hex . '</kbd></button>
                       </div>';
        }
        $output[] = '</div>';
        echo implode('', $output);
    }

    public function searchColors()
    {
        $value = $this->requestArray()['val'];
        $idInput = $this->requestArray()['idSelect'];
        $idValeInput = $this->requestArray()['idValeInput'];
        $get = ColorModel::query()->where('name', 'like', "%{$value}%");
        $output = [];
        foreach ($get as $item) {
            $output[] = '<div class="col-md-2">
                           <button class="btn btn-sm mb-1 w-100 colorButton" style="background-color: ' . $item->hex . ';color:#ffff" data-select="' . $idInput . '" data-ral="' . $item->ral_code . '" data-value="' . $idValeInput . '" data-color="' . $item->id . '" data-hex="' . $item->hex . '">' . $item->ral_code . '<br>' . $item->hex . '</button>
                       </div>';
        }
        echo implode('', $output);
    }

    public function activeOrDeactive()
    {
        $id = $this->requestArray()['id'];
        $colors = ColorModel::query()->find($id);
        $colors->color_status = ($colors->color_status == 1) ? 0 : 1;
        if ($colors->save()) {
            echo 'changeSuccess';
        }
    }

}