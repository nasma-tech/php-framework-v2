<?php

namespace App\Controllers\BankAccount;

use App\Controllers\scheme\ControllerScheme;
use App\Models\BankAccountModel\BankAccountModel;
use App\Models\BankListModel\BankListModel;

//use App\Models\BankListModel\BankListModel;

class BankAccount extends ControllerScheme
{
    const string singleName = 'حساب بانکی';
    const string pluralName = 'حساب های بانکی';
    protected string $defaultModel = BankAccountModel::class;

    public function main(): void
    {
        view->setPageTitle(self::pluralName);
        view->setSingleName(self::singleName);
        view->setPluralName(self::pluralName);
        view->ui([
            'vendors/js/tables/datatable/datatables.min',
            'vendors/js/tables/datatable/dataTables.bootstrap4.min',
            'vendors/js/tables/datatable/dataTables.buttons.min',
            'vendors/js/tables/datatable/buttons.html5.min',
            'vendors/js/tables/datatable/buttons.print.min',
            'vendors/js/tables/datatable/buttons.bootstrap.min',
            'vendors/js/tables/datatable/jszip.min',
            'vendors/js/tables/datatable/pdfmake.min',
            'vendors/js/tables/datatable/vfs_fonts',
            'vendors/js/tables/datatable/buttons.colVis.min',
            //'js/BankAccount/BankAccount'
        ],
            ['vendors/css/tables/datatable/datatables.min'],
            [
                'list' => BankAccountModel::all(),
                'bankList'=>new BankListModel(),
            ])->display('BankAccount/BankAccount.tpl');
    }

    public function addIndex(): void
    {
        $_ENV['APP_DEBUG'] = 1;
        view->setPageTitle(self::pluralName);
        view->setSingleName(self::singleName);
        view->setPluralName(self::pluralName);
        view->ui([
            'js/BankAccount/add-BankAccount'
        ], [],
            [
                'bankList' => BankListModel::all()
            ]
        )->display('BankAccount/add-BankAccount.tpl');
    }

    public function editIndex($id): void
    {
        view->setPageTitle(self::pluralName);
        view->setSingleName(self::singleName);
        view->setPluralName(self::pluralName);
        view->setModel($this->defaultModel::query()->find($id));
        view->ui([
            'js/BankAccount/add-BankAccount'
        ], [], [
            'bankList' => BankListModel::all(),
        ])->display('BankAccount/edit-BankAccount.tpl');
    }

    public function add()
    {
        $this->findBankListId();
        if (!isset($this->requestArray()['has_card_number']))
            $this->changeRequestValues('has_card_number', 0);
        if (!isset($this->requestArray()['bank_status']))
            $this->changeRequestValues('bank_status', 0);
        parent::add(); // TODO: Change the autogenerated stub
    }

    public function edit($id)
    {
        $this->findBankListId();
        if (!isset($this->requestArray()['has_card_number']))
            $this->changeRequestValues('has_card_number', 0);
        if (!isset($this->requestArray()['bank_status']))
            $this->changeRequestValues('bank_status', 0);
        return parent::edit($id); // TODO: Change the autogenerated stub
    }

    /**
     * @return void
     */
    protected function findBankListId(): void
    {
        if (isset($this->requestArray()['has_card_number'])) {
            $bankListId = 0;
            $cardNumber = substr($this->requestArray()['bank_card_number'], 0, 6);
            $bankList = BankListModel::all();
            foreach ($bankList as $bank) {
                $decode = json_decode($bank->bank_list_code, true);
                if (in_array($cardNumber, $decode)) {
                    $bankListId = $bank->id;
                }
            }
            if ($bankListId > 0)
                $this->changeRequestValues('bank_list_id', $bankListId);
            else {
                $this->failedCallBack('/BankAccount/addIndex', 'بانک یافت نشد شماره کارت وارد شده چک شود');
                die();
            }
        }
    }

    public function getAllBankAccountList(): void
    {
        $get = BankAccountModel::query()->where('bank_status', '!=', 0)->where('bank_list_id', '!=', 0)->get()->toArray();
        echo json_encode(array_map(function ($item) {
            return [
                'id' => $item['id'],
                'branchName' => $item['bank_branch_name'],
                'bankAccountNumber' => $item['bank_account_number'],
                'bankName' => BankListModel::query()->find($item['bank_list_id'])->bank_list_name
            ];
        }, $get), JSON_UNESCAPED_UNICODE);
    }
}
